/**
 * 0.9.6 composer 回填（「回滚了但消息框是空的」）。
 *
 * 专家组定案的三条根因：
 *   R2 5 个回滚入口里只有 2 个回填 → 统一 refillComposer 出口
 *   R4 afterWrite 把**裸 uuid** 传给 openSession → `unknown session` 必抛且被
 *      `catch {}` 静默吞掉 → 视图重建从没生效过
 *   R1 目标会选到宿主注入的伪 user 行（通知），回填文本不是用户写的那句
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const src = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'client.js'), 'utf8')

/** 与 refillComposer 同构的边界选择 */
const pickForRefill = (rows, boundarySeq) => {
  const hit = rows.filter((r) => r && typeof r.seq === 'number' && r.seq <= boundarySeq && r.fullText)
  return hit.length ? hit[hit.length - 1] : null
}

/** 与 client.js 的 injected 同构（从源码里截出正则字面量校验覆盖面） */
const injectedSource = (() => {
  const m = src.match(/const injected = \(?raw\)? =>\s*(\/[\s\S]*?\/[gimsuy]*)\.test/)
  return m ? new RegExp(m[1].slice(1, m[1].lastIndexOf('/')), m[1].slice(m[1].lastIndexOf('/') + 1)) : null
})()

test('/undo：boundary 就是被回滚那条 → 回填它自己', () => {
  const rows = [
    { seq: 8,  fullText: '第一句' },
    { seq: 54, fullText: '要撤销的这句' },
    { seq: 89, fullText: '重放副本' },
  ]
  assert.equal(pickForRefill(rows, 54).fullText, '要撤销的这句')
})

test('AI 时钟按钮：boundary 是 AI 消息 → 取它之前那条用户消息', () => {
  const rows = [
    { seq: 8,  fullText: '我问的问题' },
    { seq: 18, fullText: null },              // assistant 没有 fullText
    { seq: 54, fullText: '下一句' },
  ]
  // boundary = 18（AI 消息 seq）
  assert.equal(pickForRefill(rows, 18).seq, 8, '取边界之前最后一条带全文的')
  // 边界之后的不该被取到
  assert.equal(pickForRefill(rows, 54).seq, 54)
})

test('无可用行 → 返回 null（调用方不回填，不写空串）', () => {
  assert.equal(pickForRefill([], 100), null)
  assert.equal(pickForRefill([{ seq: 5, fullText: null }], 100), null)
  assert.equal(pickForRefill([{ seq: 500, fullText: 'x' }], 100), null, '只在边界之后的不能被取到')
})

test('R4：afterWrite 必须传带 session- 前缀的 id 给 openSession', () => {
  const m = src.match(/var afterWrite = \([\s\S]*?\n    \}/)
  assert.ok(m, '找不到 afterWrite')
  assert.ok(/openSession\(rawSid\)/.test(m[0]),
    'openSession 收到裸 uuid 会抛 `sessions.retain: unknown session`，外层 catch {} 静默 → 视图重建从未生效')
  assert.ok(!/openSession\(bare\)|openSession\(bareSessionId/.test(m[0]),
    '不得传裸 id')
})

test('R2：所有 revert 入口都接了 refillComposer', () => {
  const calls = (src.match(/\brefillComposer\(/g) || []).length
  // 0.19.0：三个入口 —— runUndo(/undo) + runUserRevert(悬停) + OpsPanel(A 抽屉)。
  // 已删：行内编辑按钮（交给 message-edit 插件）、AI 时钟回撤 runRevert
  //（用户要求删除，回撤只属于用户消息）。
  // 注意：定义写法是 `refillComposer = (`，不匹配 `refillComposer(`
  assert.equal(calls, 3, `refillComposer 调用 ${calls} 处，应为 3 个回滚入口`)
  assert.ok(/var refillComposer = \(/.test(src), '缺 refillComposer 定义')
  // 反例：restore / redo 不该回填（它们是加回内容，不是删）
  const redo = src.match(/var runRedo = \(\) => \{[\s\S]*?\n    \}/)
  assert.ok(redo && !/refillComposer\(/.test(redo[0]), '/redo 不应回填 composer')
})

